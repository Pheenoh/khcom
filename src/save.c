void ShowSramErrorScreen(void) {
    vu16* ime;
    vu16* ie;
    vu16* dispstat;
    vu16* dispcnt;
    vu16* p;
    vu32* dma;

    ime = (vu16*)REG_ADDR_IME;
    *ime = 0;
    ie = (vu16*)REG_ADDR_IE;
    *ie |= INTR_FLAG_VBLANK;
    dispstat = (vu16*)REG_ADDR_DISPSTAT;
    *dispstat |= DISPSTAT_VBLANK_INTR;
    *ime = 1;
    p = (vu16*)REG_ADDR_BG0CNT;
    do {
        *p = 0x88;
    } while (0);
    p += 0x24;
    *p = 0x3FBF;
    p += 2;
    *p = 0x10;
    dispcnt = (vu16*)REG_ADDR_DISPCNT;
    *dispcnt = (DISPCNT_BG0_ON | DISPCNT_OBJ_ON);
    VBlankIntrWait();
    dma = (vu32*)REG_ADDR_DMA3;
    dma[0] = (u32)gSramErrorTiles;
    dma[1] = 0x06008000;
    dma[2] = (DMA_ENABLE << 16) | 0x2000;
    dma[2];
    dma[0] = (u32)gSramErrorPalette;
    dma[1] = 0x05000000;
    dma[2] = (DMA_ENABLE << 16) | 0x100;
    dma[2];
    dma[0] = (u32)gSramErrorTilemap;
    dma[1] = (u32)gSramErrorTilemapBuf;
    dma[2] = (DMA_ENABLE << 16) | 0x280;
    dma[2];
    dma[0] = (u32)gSramErrorTilemapBuf;
    dma[1] = 0x06000000;
    dma[2] = (DMA_ENABLE << 16) | 0x400;
    dma[2];
    WaitSramErrorInput();
    *ime = 0;
    *ie &= ~INTR_FLAG_VBLANK;
    *dispstat &= ~DISPSTAT_VBLANK_INTR;
    *ime = 1;
    *dispcnt = 0;
}

void WaitSramErrorInput(void) {
    vu16* bldy;
    vu16* bldy2;
    vu32* dma;
    s32 i;
    u32 j;
    s32 prev;
    s32 cur;
    s32 ok;

    i = 0;
    ok = 0;
    cur = 0;
    prev = 0;
    j = 0;
    bldy = (vu16*)REG_ADDR_BLDY;
    do {
        VBlankIntrWait();
        *bldy = 16 - j;
        j++;
    } while (j <= 16);

    if (i <= 19) {
        dma = (vu32*)REG_ADDR_DMA3;
        do {
            ReadKeysRaw();

            if ((((gRawKeysPrev ^ gRawKeys) & gRawKeys) & DPAD_ANY) == DPAD_ANY) {
                prev = cur;
                cur = i;
            }

            if (prev != 0 && cur - prev <= 3) {
                ok = 1;
            }
            i++;
            VBlankIntrWait();
            dma[0] = (u32)gSramErrorTilemapBuf;
            dma[1] = 0x06000000;
            dma[2] = ((DMA_ENABLE | DMA_32BIT) << 16) | 0x200;
            dma[2];
        } while (i <= 19);
    }

    j = 0;
    bldy2 = (vu16*)REG_ADDR_BLDY;
    do {
        VBlankIntrWait();
        *bldy2 = j;
        j++;
    } while (j <= 16);

    if (ok) {
        gSystemFlags |= 4;
    } else {
        gSystemFlags &= 0xFFFB;
    }
}

void ReadKeysRaw(void) {
    u16 keys = KEYS_MASK ^ REG_KEYINPUT;

    gRawKeysPrev = gRawKeys;
    gRawKeys = keys;
}
