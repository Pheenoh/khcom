void ZeroFill(void* dst, s16 size) {
    u16 zero;
    u16* p;
    vu32* dma;

    if (size & 1) {
        ((u8*)dst)[size - 1] = 0;
    }

    p = &zero;
    *p = 0;
    dma = (vu32*)REG_ADDR_DMA3;
    dma[0] = (u32)p;
    dma[1] = (u32)dst;
    dma[2] = 0x81000000 | (size / 2);
    dma[2];
}

void CopyBytes(const u8* src, u8* dst, s16 len) {
    s16 i;

    for (i = 0; i < len; i++) {
        dst[i] = src[i];
    }
}

u8 BytesEqual(const u8* a, const u8* b, s16 len) {
    s16 i;

    for (i = 0; i < len; i++) {
        if (a[i] != b[i]) {
            return 0;
        }
    }

    return 1;
}

u16 SaveChecksum(u16* data, int size) {
    u32 sum;
    s16 len;

    len = size;
    sum = 0;
    
    while (len > 1) {
        sum += *data++;
        len -= 2;
    }

    if (len > 0) {
        sum += *(u8*)data;
    }
    
    sum = (sum & 0xFFFF) + (sum >> 16);
    return ~(sum + (sum >> 16));
}

int SaveVerifyBlock(u8* sram, u8* hdr, u8* buf, s16 size) {
    int ret;

    ZeroFill(buf, size);
    ReadSramFast(sram, buf, size);
    
    if (BytesEqual(hdr, gSaveSignature, SAVE_SIGNATURE_SIZE)) {
        ret = (SaveChecksum((u16*)buf, size) == 0) ? SAVE_OK : SAVE_BAD_CHECKSUM;
    } else {
        ret = SAVE_BAD_SIGNATURE;
    }

    return ret;
}

