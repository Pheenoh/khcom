/* Zero-fill a buffer using DMA3 16-bit fill (src fixed on a stack zero).
   An odd trailing byte is cleared manually first. */
void func_080089E0(void *dst, s16 size)
{
    u16 zero;
    u16 *p;
    vu32 *dma;

    if (size & 1) {
        ((u8 *)dst)[size - 1] = 0;
    }
    p = &zero;
    *p = 0;
    dma = (vu32 *)0x40000D4;
    dma[0] = (u32)p;
    dma[1] = (u32)dst;
    dma[2] = 0x81000000 | (size / 2);
    dma[2];
}
